#!/usr/bin/env python3
"""Independent read-only third-hour G22 original-vs-native intermediate audit.

The original CALMET 6h DIAGNO trace is pinned, NEVER passed to C++.
The native one-hour trace must be independently generated by G66 from
native hour2 committed P6F and current G26A WIND1/FRADJ. No thresholds
are invented or relaxed: report bitwise and absolute discrepancies, but
do not promote this to S4/P6 scientific admission.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

from scripts.s4.s4r1c9l_original_g22_trace import HEADER, STAGE_ARRAYS, NX, NY, NZ

NC = NX * NY
ORIGINAL_TRACE_SHA = "b6d96dab81af8e9cba89ef55d386aba8082d9136aa7ef569ad0f9e39f1e31869"
GEO_SHA = "5feaa58e5835576b3ae2c03a51e955114d620a7aeb710ded58a9f999695f602a"


def sha(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for part in iter(lambda: f.read(1024 * 1024), b""):
            h.update(part)
    return h.hexdigest()


def extract(raw: bytes, hours: tuple[int, ...]) -> dict[int, dict[int, bytes]]:
    offset = 0
    result: dict[int, dict[int, bytes]] = {}
    for hour in hours:
        stage_payloads = {}
        for stage, fields in STAGE_ARRAYS.items():
            if offset + HEADER.size > len(raw):
                raise ValueError("G22 trace truncated header")
            header = HEADER.unpack_from(raw, offset)
            offset += HEADER.size
            if header != (hour, NX, NY, NZ, stage):
                raise ValueError(f"G22 trace wrong hour/grid/stage: {header}")
            size = NC * (NZ if stage == 50 else 1) * len(fields) * 4
            if offset + size > len(raw):
                raise ValueError("G22 trace truncated REAL4 array")
            stage_payloads[stage] = raw[offset:offset + size]
            offset += size
        result[hour] = stage_payloads
    if offset != len(raw):
        raise ValueError("G22 trace has trailing bytes")
    return result


def frozen_limit(field_name: str, original: float) -> float:
    # Existing, PRE-REGISTERED tolerances, not fitted to these results:
    # ISSUE40_S4R1C3_REAL_MISSFC_LAND_THERMAL_20261021.md
    # and ISSUE40_S4_P6B2B_REAL_G22_SLOPE_20261020.md.
    if field_name == "temp2d":
        return 0.001  # K
    if field_name == "qsw":
        return 0.005  # W/m2
    if field_name == "qh":
        return 0.25   # W/m2
    if field_name == "rho":
        return 0.0001 # kg/m3
    if field_name == "ustar":
        return 0.005  # m/s
    if field_name == "el":
        return max(0.5, 0.01 * abs(original)) # m
    if field_name in ("uslope", "vslope"):
        return 0.0002 # m/s, original G11/G22 slope threshold
    raise ValueError("unregistered G22 field tolerance")


def compare_words(a: bytes, b: bytes, stride: int, field: int,
                  water: set[int], field_name: str | None = None) -> dict:
    if len(a) != len(b) or len(a) % (4 * stride):
        raise ValueError("G22 original/native field byte length mismatch")
    count = len(a) // (4 * stride)
    if count not in (NC, NC * NZ) or not 0 <= field < stride:
        raise ValueError("G22 original/native field shape mismatch")
    bitwise = 0
    max_abs = 0.0
    max_rel = 0.0
    sum_abs = 0.0
    first = None
    mismatched_water = 0
    mismatched_land = 0
    frozen_exceedances = 0
    worst_exceedance = None
    for cell in range(count):
        offset = 4 * (stride * cell + field)
        original = a[offset:offset + 4]
        native = b[offset:offset + 4]
        av, = struct.unpack("<f", original)
        bv, = struct.unpack("<f", native)
        if not (math.isfinite(av) and math.isfinite(bv)):
            raise ValueError("nonfinite original/native G22 REAL4")
        if original == native:
            bitwise += 1
        else:
            if first is None:
                first = {
                    "i": cell % NX + 1, "j": (cell // NX) % NY + 1,
                    "k": cell // NC + 1, "original": av, "native": bv,
                }
            if cell % NC in water:
                mismatched_water += 1
            else:
                mismatched_land += 1
        diff = abs(av - bv)
        if field_name is not None and diff > frozen_limit(field_name, av):
            frozen_exceedances += 1
            if worst_exceedance is None:
                worst_exceedance = {
                    "i": cell % NX + 1, "j": (cell // NX) % NY + 1,
                    "k": cell // NC + 1, "original": av, "native": bv,
                    "abs_diff": diff, "limit": frozen_limit(field_name, av),
                }
        sum_abs += diff
        max_abs = max(max_abs, diff)
        max_rel = max(max_rel, diff / max(abs(av), abs(bv), 1e-20))
    return {
        "count": count, "bitwise_equal": bitwise,
        "bitwise_unequal": count - bitwise,
        "water_bitwise_unequal": mismatched_water,
        "land_bitwise_unequal": mismatched_land,
        "max_abs": max_abs, "max_relative": max_rel,
        "mean_abs": sum_abs / count, "first_mismatch": first,
        "frozen_tolerance_exceedances": frozen_exceedances,
        "first_frozen_exceedance": worst_exceedance,
    }


def compare(original: dict[int, bytes], native: dict[int, bytes],
            water: set[int]) -> dict:
    if len(water) != 63 or any(not 0 <= cell < NC for cell in water):
        raise ValueError("G22 independent GEO WATER mask drift")
    fields = {}
    total = equal = frozen_exceedances = 0
    for stage, names in STAGE_ARRAYS.items():
        a, b = original[stage], native[stage]
        for field, name in enumerate(names):
            stat = compare_words(a, b, len(names), field, water, name)
            fields[f"{stage}:{name}"] = stat
            total += stat["count"]
            equal += stat["bitwise_equal"]
            frozen_exceedances += stat["frozen_tolerance_exceedances"]
    water_history_equal = all(
        fields[f"40:{name}"]["water_bitwise_unequal"] == 0
        for name in ("ustar", "el")
    )
    return {
        "status": "PASS_SCOPED_FROZEN_G22_INTERMEDIATES" if (
                    frozen_exceedances == 0 and water_history_equal)
                  else "FAIL_FROZEN_G22_INTERMEDIATES",
        "bitwise_status": "PASS_EXACT_BITWISE" if equal == total
                          else "FAIL_EXACT_BITWISE_DIFFERENCES",
        "tolerance_authority": [
            "docs/plans/ISSUE40_S4R1C3_REAL_MISSFC_LAND_THERMAL_20261021.md",
            "docs/plans/ISSUE40_S4_P6B2B_REAL_G22_SLOPE_20261020.md",
        ],
        "frozen_tolerance_exceedances": frozen_exceedances,
        "fields": fields, "compared_real4": total,
        "bitwise_equal": equal, "bitwise_unequal": total - equal,
        "water_ustar_el_native_history_bitwise_equal": water_history_equal,
        "native_hour3_g22_production_guard": "UNCHANGED_REJECTS",
        "hour3_g14_state_committed": False,
        "s4_p6_sixhour_science": "NOT_ACCEPTED",
        "s4_p7": "NOT_ACCEPTED",
        "independent_science_review": "NOT_RUN",
    }


def run(original_path: Path, native_path: Path, geo_path: Path,
        expected_native_sha: str) -> dict:
    if sha(original_path) != ORIGINAL_TRACE_SHA:
        raise ValueError("original source trace SHA drift")
    if sha(geo_path) != GEO_SHA:
        raise ValueError("authentic original GEO SHA drift")
    if len(expected_native_sha) != 64 or sha(native_path) != expected_native_sha:
        raise ValueError("native G66 trace SHA differs from operator pin")
    from native_cpp.reference.compare_p3_makegeo_dynamic import parse_geo
    grid = parse_geo(geo_path, nx=NX, ny=NY, zone=50, hem="N",
                     x0=426.590, y0=3464.125, dx=1.)
    water = {i for i, lu in enumerate(grid["category"])
             if 50 <= int(lu) <= 55}
    if len(water) != 63:
        raise ValueError("original GEO WATER mask is not 63")
    original = extract(original_path.read_bytes(), tuple(range(2, 8)))
    native = extract(native_path.read_bytes(), (4,))
    result = compare(original[4], native[4], water)
    result["original_trace_sha256"] = ORIGINAL_TRACE_SHA
    result["native_trace_sha256"] = expected_native_sha
    result["original_geo_sha256"] = GEO_SHA
    result["original_hour_end_utc"] = 4
    result["native_hour_end_utc"] = 4
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("original_trace", "native_trace", "geo", "report"):
        parser.add_argument("--" + name.replace("_", "-"),
                            type=Path, required=True)
    parser.add_argument("--expected-native-sha256", required=True)
    args = parser.parse_args()
    if args.report.exists():
        raise ValueError("refuse overwrite existing science report")
    result = run(args.original_trace, args.native_trace, args.geo,
                 args.expected_native_sha256)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(result, indent=2) + "\n")
    print(result["status"], result["bitwise_equal"],
          "/", result["compared_real4"], "bitwise values")
    for name, stat in result["fields"].items():
        print(name, "bitwise_diff", stat["bitwise_unequal"],
              "max_abs", stat["max_abs"])
    if result["status"] != "PASS_SCOPED_FROZEN_G22_INTERMEDIATES":
        raise SystemExit(3)


if __name__ == "__main__":
    main()
